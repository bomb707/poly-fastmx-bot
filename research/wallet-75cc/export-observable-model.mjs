#!/usr/bin/env node
// Convert the frozen research artifact into a dependency-free runtime module.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const cohortDir = path.resolve(process.argv[2]
  || path.join(root, "data/wallet-75cc/exact-2026-08-20_2026-08-27"));
const outputFile = path.resolve(process.argv[3]
  || path.join(root, "engine/strategies/target75cc-release-model.js"));
const modelFile = path.join(cohortDir, "observable-cap-policy-model.json");
const evaluationFile = path.join(cohortDir, "observable-menu-evaluation.json");
const report = JSON.parse(fs.readFileSync(modelFile));
const evaluation = JSON.parse(fs.readFileSync(evaluationFile));
const sha256 = (file) => crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
const meta = {
  discovery: report.discovery,
  modelSha256: sha256(modelFile),
  evaluationSha256: sha256(evaluationFile),
  excluded: report.exclusions,
  rankMetrics: report.metrics,
  autonomousParity: {
    selection: evaluation.causality.selection,
    train: evaluation.selected.train,
    validation: evaluation.selected.validation,
    holdout: evaluation.selected.holdout,
  },
};
const source = `// Generated by research/wallet-75cc/export-observable-model.mjs.\n`
  + `// Observable imitation only: public evidence cannot identify private wallet code.\n`
  + `export const RELEASE_MODEL = ${JSON.stringify(report.model)};\n`
  + `export const RELEASE_POLICY = ${JSON.stringify(evaluation.selected.config)};\n`
  + `export const RELEASE_META = ${JSON.stringify(meta)};\n`;
fs.writeFileSync(outputFile, source);
console.log(JSON.stringify({ outputFile, modelSha256: meta.modelSha256,
  policy: evaluation.selected.config, holdout: evaluation.selected.holdout }, null, 2));
